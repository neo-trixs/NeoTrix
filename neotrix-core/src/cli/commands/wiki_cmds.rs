#[derive(Default)]
struct CodebaseStats { file_count: usize, total_lines: usize, module_count: usize, layers: BTreeMap<String, LayerInfo>, domains: BTreeMap<String, DomainInfo>, key_types: Vec<TypeInfo>, cli_commands: Vec<CmdInfo> }
struct LayerInfo { path: String, files: usize, lines: usize }
struct DomainInfo { path: String, files: usize, lines: usize }
struct TypeInfo { name: String, file: String, kind: String }
struct CmdInfo { name: String, description: String }

fn detect_project_name(root: &Path) -> String {
    let cargo = root.join("Cargo.toml");
    if cargo.exists() {
        if let Ok(content) = std::fs::read_to_string(&cargo) {
            for line in content.lines() {
                let trimmed = line.trim();
                if let Some(name) = trimmed.strip_prefix("name = \"") {
                    if let Some(end) = name.find('"') {
                        return name[..end].to_string();
                    }
                }
            }
        }
    }
    "NeoTrix".to_string()
}

fn collect_stats(src_dir: &Path) -> Result<CodebaseStats, String> {
    let mut stats = CodebaseStats::default();
    if !src_dir.exists() { return Err(format!("Source dir not found: {}", src_dir.display())); }
    let mut dirs_to_scan: Vec<std::path::PathBuf> = vec![src_dir.to_path_buf()];
    let mut seen_dirs = std::collections::HashSet::new();
    let mut key_types_seen = std::collections::HashSet::new();
    while let Some(dir) = dirs_to_scan.pop() {
        if !seen_dirs.insert(dir.clone()) { continue; }
        let entries = match std::fs::read_dir(&dir) { Ok(e) => e, Err(_) => continue };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() { dirs_to_scan.push(path.clone()); }
            else if path.extension().is_some_and(|ext| ext == "rs") {
                let relative = path.strip_prefix(src_dir.parent().unwrap_or(Path::new("."))).unwrap_or(&path).display().to_string();
                let content = match std::fs::read_to_string(&path) { Ok(c) => c, Err(_) => continue };
                let line_count = content.lines().count();
                stats.file_count += 1; stats.total_lines += line_count;
                let path_str = path.display().to_string();
                for (layer_key, layer_prefix) in &[("L0 Substrate","l0_substrate"),("L1 Body","l1_body"),("L2 World","l2_world"),("L3 Memory","l3_memory"),("L4 Cognition","l4_cognition"),("L5 Consciousness","l5_consciousness"),("L6 Self","l6_self"),("L7 Capability","l7_capability"),("L8 Autonomic","l8_autonomic"),("L9 Transcendent","l9_transcendent")] {
                    if path_str.contains(layer_prefix) {
                        let entry = stats.layers.entry(layer_key.to_string()).or_insert_with(|| LayerInfo { path: format!("src/{}", layer_prefix), files: 0, lines: 0 });
                        entry.files += 1; entry.lines += line_count; break;
                    }
                }
                for component in path.components() {
                    if let std::path::Component::Normal(name) = component {
                        let name_str = name.to_string_lossy();
                        if name_str.starts_with("nt_") && name_str.contains('_') {
                            let entry = stats.domains.entry(name_str.to_string()).or_insert_with(|| DomainInfo { path: relative.clone(), files: 0, lines: 0 });
                            entry.files += 1; entry.lines += line_count; break;
                        }
                    }
                }
                for line in content.lines() {
                    let trimmed = line.trim();
                    for prefix in ["pub struct ", "struct ", "pub trait ", "trait ", "pub enum ", "enum "] {
                        if let Some(name) = trimmed.strip_prefix(prefix) {
                            if let Some(end) = name.find(|c: char| !c.is_alphanumeric() && c != '_') {
                                let type_name = name[..end].to_string();
                                if key_types_seen.insert(type_name.clone()) {
                                    let kind = if prefix.contains("struct") { "struct" } else if prefix.contains("trait") { "trait" } else { "enum" };
                                    stats.key_types.push(TypeInfo { name: type_name, file: relative.clone(), kind: kind.to_string() });
                                }
                            }
                        }
                    }
                }
                if path_str.contains("cli/commands") && !path_str.ends_with("mod.rs") && !path_str.ends_with("types.rs") && !path_str.ends_with("registry.rs") {
                    for line in content.lines() {
                        let trimmed = line.trim();
                        if let Some(rest) = trimmed.strip_prefix("fn name(&self) -> &str {") {
                            let cmd_name = rest.trim().trim_matches(|c: char| c == ' ' || c == '"' || c == '{' || c == '}').to_string();
                            if !cmd_name.is_empty() {
                                let desc_text = content.lines().find_map(|l| {
                                    let t = l.trim();
                                    t.strip_prefix("fn description(&self) -> &str {").and_then(|s| {
                                        let clean = s.trim().trim_matches(|c: char| c == ' ' || c == '"' || c == '{' || c == '}').to_string();
                                        if !clean.is_empty() { Some(clean) } else { None }
                                    })
                                }).unwrap_or_default();
                                stats.cli_commands.push(CmdInfo { name: format!("/{}", cmd_name), description: desc_text });
                                break;
                            }
                        }
                    }
                }
            }
        }
    }
    let mut mod_dirs = std::collections::HashSet::new();
    let mut scan_dirs: Vec<std::path::PathBuf> = vec![src_dir.to_path_buf()];
    while let Some(dir) = scan_dirs.pop() {
        if dir.join("mod.rs").exists() { mod_dirs.insert(dir.clone()); }
        if let Ok(entries) = std::fs::read_dir(&dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_dir() { scan_dirs.push(path); }
            }
        }
    }
    stats.module_count = mod_dirs.len();
    stats.key_types.sort_by(|a, b| a.name.cmp(&b.name));
    stats.key_types.truncate(50);
    Ok(stats)
}

fn build_tree(root: &Path, depth: usize, max_depth: usize) -> String {
    if depth > max_depth { return String::new(); }
    let mut out = String::new();
    let entries = match std::fs::read_dir(root) { Ok(e) => e, Err(_) => return out };
    let mut items: Vec<_> = entries.flatten().filter(|e| {
        let name = e.file_name(); let name_str = name.to_string_lossy();
        !name_str.starts_with('.') && !name_str.starts_with("target") && !name_str.starts_with("node_modules") && name_str != "Cargo.lock"
    }).collect();
    items.sort_by_key(|e| (!e.file_type().map(|t| t.is_dir()).unwrap_or(false), e.file_name().to_string_lossy().to_string()));
    for item in &items {
        let name = item.file_name().to_string_lossy().to_string();
        let indent = "  ".repeat(depth);
        if item.file_type().map(|t| t.is_dir()).unwrap_or(false) {
            out.push_str(&format!("{}{}/\n", indent, name));
            out.push_str(&build_tree(&item.path(), depth + 1, max_depth));
        } else if name.ends_with(".rs") || name == "Cargo.toml" || name.ends_with(".md") {
            out.push_str(&format!("{}{}\n", indent, name));
        }
    }
    out
}
