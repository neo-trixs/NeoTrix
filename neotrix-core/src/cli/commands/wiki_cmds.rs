fn cmd_generate() -> CommandOutput {
    let root = Path::new(".");
    let project_name = detect_project_name(root);
    let src_dir = root.join("neotrix-core").join("src");
    let stats = match collect_stats(&src_dir) {
        Ok(s) => s,
        Err(e) => return CommandOutput::err(&format!("Failed to scan source tree: {}", e)),
    };
    let mut md = String::new();
    md.push_str(&format!("# {} — Wiki (Auto-generated)\n\n", project_name));
    md.push_str(&format!("> Auto-generated by `/wiki generate` on {}\n\n", chrono::Local::now().format("%Y-%m-%d %H:%M:%S")));
    md.push_str("## Codebase Overview\n\n| Metric | Value |\n|--------|-------|\n");
    md.push_str(&format!("| Total `.rs` files | {} |\n", stats.file_count));
    md.push_str(&format!("| Total lines of code | {} |\n", stats.total_lines));
    md.push_str(&format!("| Modules (subdirectories with mod.rs) | {} |\n", stats.module_count));
    md.push_str(&format!("| Source root | `{}` |\n", src_dir.display()));
    md.push('\n');
    md.push_str("## Layer Architecture\n\n| Layer | Directory | Files | Lines |\n|-------|-----------|-------|-------|\n");
    for (layer, info) in &stats.layers {
        md.push_str(&format!("| `{}` | `{}` | {} | {} |\n", layer, info.path, info.files, info.lines));
    }
    md.push('\n');
    md.push_str("## Project Structure\n\n```\n");
    md.push_str(&build_tree(root, 0, 3));
    md.push_str("```\n\n");
    md.push_str("## Build & Test\n\n```bash\ncargo build -p neotrix\ncargo build --features full --lib -p neotrix\ncargo test -p neotrix --lib\ncargo check --lib -p neotrix\n```\n\n");
    md.push_str("## Architecture Domains\n\n| Domain | Prefix | Files | Lines |\n|--------|--------|-------|-------|\n");
    for (domain, info) in &stats.domains {
        md.push_str(&format!("| {} | `{}` | {} | {} |\n", domain, info.path, info.files, info.lines));
    }
    md.push('\n');
    if !stats.key_types.is_empty() {
        md.push_str("## Key Types & Traits\n\n| Type/Trait | File | Kind |\n|------------|------|------|\n");
        for kt in &stats.key_types {
            md.push_str(&format!("| `{}` | `{}` | {} |\n", kt.name, kt.file, kt.kind));
        }
        md.push('\n');
    }
    if !stats.cli_commands.is_empty() {
        md.push_str("## CLI Commands\n\n| Command | Description |\n|---------|-------------|\n");
        for cmd in &stats.cli_commands {
            md.push_str(&format!("| `{}` | {} |\n", cmd.name, cmd.description));
        }
        md.push('\n');
    }
    match std::fs::write(root.join("AGENTS.md"), &md) {
        Ok(()) => CommandOutput::ok(&format!("AGENTS.md written: {} bytes, {} files, {} lines", md.len(), stats.file_count, stats.total_lines)),
        Err(e) => CommandOutput::err(&format!("Failed to write AGENTS.md: {}", e)),
    }
}

fn cmd_status() -> CommandOutput {
    let path = Path::new("AGENTS.md");
    if !path.exists() {
        return CommandOutput::not_found("AGENTS.md does not exist");
    }
    let meta = match path.metadata() {
        Ok(m) => m,
        Err(e) => return CommandOutput::err(&format!("Cannot read metadata: {}", e)),
    };
    let size = meta.len();
    let modified = meta.modified().ok();
    let age_str = modified
        .and_then(|m| SystemTime::now().duration_since(m).ok())
        .map(|d| {
            let secs = d.as_secs();
            if secs < 60 { format!("{}s ago", secs) }
            else if secs < 3600 { format!("{}m {}s ago", secs / 60, secs % 60) }
            else if secs < 86400 { format!("{}h {}m ago", secs / 3600, (secs % 3600) / 60) }
            else { format!("{}d {}h ago", secs / 86400, (secs % 86400) / 3600) }
        })
        .unwrap_or_else(|| "unknown".to_string());
    CommandOutput::ok(&format!("AGENTS.md: {} bytes, modified {}", size, age_str))
}

