pub struct WikiCmd;

impl CliCommand for WikiCmd {
    fn name(&self) -> &str {
        "/wiki"
    }

    fn description(&self) -> &str {
        "Wiki: generate AGENTS.md | sync docs to KB | graph | search"
    }
    fn is_primary(&self) -> bool { false }


    fn execute(
        &self,
        args: &[String],
        _brain: Option<&Arc<RwLock<SelfIteratingBrain>>>,
    ) -> CommandOutput {
        if args.is_empty() {
            return CommandOutput::ok(
                "Wiki commands:\n  /wiki generate       AGENTS.md auto-gen\n  /wiki status         AGENTS.md status\n  /wiki sync [dir]     sync docs/ -> KB wiki\n  /wiki graph [file]   generate wiki graph HTML\n  /wiki query <text>   search KB wiki pages",
            );
        }
        match args[0].as_str() {
            "generate" => cmd_generate(),
            "status" => cmd_status(),
            "sync" => cmd_sync(args),
            "graph" => cmd_graph(args),
            "query" => cmd_query(args),
            _ => CommandOutput::err(&format!("Unknown subcommand: {}", args[0])),
        }
    }
}

fn cmd_sync(args: &[String]) -> CommandOutput {
    let dir = args.get(1).map(|s| s.as_str()).unwrap_or("docs");
    let dir_path = Path::new(dir);
    if !dir_path.exists() {
        return CommandOutput::err(&format!("Directory not found: {}", dir));
    }
    let kb = match KnowledgeBase::open(None) {
        Ok(kb) => kb,
        Err(e) => return CommandOutput::err(&format!("Cannot open KB: {}", e)),
    };
    match kb.wiki_sync(dir_path, dir) {
        Ok(report) => {
            let mut msg = format!("Wiki sync: {} pages, {} edges", report.synced, report.edges_created);
            if !report.errors.is_empty() {
                msg.push_str(&format!(" ({} errors)", report.errors.len()));
                for (stem, err) in report.errors.iter().take(5) {
                    msg.push_str(&format!("\n  {}: {}", stem, err));
                }
            }
            CommandOutput::ok(&msg)
        }
        Err(e) => CommandOutput::err(&format!("Wiki sync failed: {}", e)),
    }
}

fn cmd_graph(args: &[String]) -> CommandOutput {
    let output = args.get(1).map(|s| s.as_str()).unwrap_or("wiki-graph.html");
    let kb = match KnowledgeBase::open(None) {
        Ok(kb) => kb,
        Err(e) => return CommandOutput::err(&format!("Cannot open KB: {}", e)),
    };
    match kb.wiki_graph_html() {
        Ok(html) => match std::fs::write(output, &html) {
            Ok(()) => CommandOutput::ok(&format!("Wiki graph written to {}", output)),
            Err(e) => CommandOutput::err(&format!("Failed to write {}: {}", output, e)),
        },
        Err(e) => CommandOutput::err(&format!("Wiki graph failed: {}", e)),
    }
}

fn cmd_query(args: &[String]) -> CommandOutput {
    if args.len() < 2 {
        return CommandOutput::err("Usage: /wiki query <text>");
    }
    let query = args[1..].join(" ");
    let kb = match KnowledgeBase::open(None) {
        Ok(kb) => kb,
        Err(e) => return CommandOutput::err(&format!("Cannot open KB: {}", e)),
    };
    match kb.wiki_query(&query, 20) {
        Ok(results) => {
            if results.is_empty() {
                return CommandOutput::ok("No wiki pages found.");
            }
            let mut msg = format!("Wiki results for \"{}\":\n", query);
            for (i, r) in results.iter().enumerate() {
                let s = if r.summary.len() > 80 { format!("{}...", &r.summary[..77]) } else { r.summary.clone() };
                msg.push_str(&format!("  {}. {} (score: {:.2})\n     {}\n", i + 1, r.title, r.score, s));
            }
            CommandOutput::ok(&msg)
        }
        Err(e) => CommandOutput::err(&format!("Wiki query failed: {}", e)),
    }
}

