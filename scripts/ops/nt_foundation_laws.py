def prior_pmap(path=None, known=None):
    """旧原理 P-id → 活库 M-id，读账本 axioms.json（不再用号段猜）。

    账本缺失/不可解析 → SystemExit：没有账本就只能靠号段猜，而号段就是
    本次悬空边的根因，宁可停。账本里的 mid 逐条与活库核对，对不上即退出。
    """
    path = path or AXIOMS_JSON
    try:
        with open(path, encoding="utf-8") as fh:
            rows = json.load(fh)
    except (OSError, ValueError) as e:
        raise SystemExit(
            "ABORT: 读不到原理账本 %s（%s）—— 旧原理的 M-id 只能从账本取。"
            "历史实现靠 30 段硬编码基址（479545…480475）推算，那批 id 在活库"
            "从不存在，产出全是悬空边；此处不再回退。" % (path, type(e).__name__))
    if known is None:
        known = live_mid_set()
    pmap, dead = {}, []
    for a in rows:
        pid, mid = a.get("id", ""), a.get("mid", "")
        if not pid or not mid:
            continue
        pmap[pid] = mid
        if mid not in known:
            dead.append("%s→%s" % (pid, mid))
    if dead:
        raise SystemExit(
            "ABORT: 账本 %s 里 %d 条 mid 在活库 %s 中不存在（如 %s）—— "
            "写下去就是永久悬空边。请先校正账本，不要绕过。"
            % (path, len(dead), COCOONS, "、".join(sorted(dead)[:5])))
    return pmap


def resolve_ref(x, pmap, anchors):
    """XREFS 条目 → 活库 M-id：P-id 走账本，@hub/@atlas 走卦符反查。"""
    if x == REF_HUB:
        return anchors["hub"]
    if x == REF_ATLAS:
        return anchors["atlas"]
    return pmap.get(x, "")


def build_batch(laws, demo_q, demo_uses, demo_a, outfile, force, xrefs=None):
    if os.path.exists(outfile) and not force:
        print("skip: %s exists (use --force to rebuild)" % outfile)
        return None
    mx, _ = scan_max_mid(COCOONS)
    start = mx + 1
    # 卦符证据与跨代哨兵一律运行时反查（任一环查不到即 SystemExit）
    sym = live_symbol_mids()
    anchors = {"hub": sym.get(HUB_HEX, ""), "atlas": live_atlas_mid()}
    if not anchors["hub"]:
        raise SystemExit("ABORT: 活库 %s 域缺脑中枢卦 %r —— 无法给证据链兜底。"
                         % (SYMBOL_DOMAIN, HUB_HEX))
    pmap = prior_pmap()
    try:
        with open(AXIOMS_JSON, encoding="utf-8") as fh:
            _ax = json.load(fh)
            have = {a["id"] for a in _ax}
            have_titles = {a["text"] for a in _ax}
    except (OSError, ValueError):
        have, have_titles = set(), set()
    laws = [l for l in laws
            if l[0] not in have and l[1] not in have_titles]
    if not laws:
        print("skip: all ids already in axioms")
        return None
    missing = [p for p in demo_uses if p not in pmap]
    if missing:
        raise SystemExit(
            "ABORT: 演示题 %s 引用 %s，但账本 %s 里查不到这些 P-id —— "
            "旧原理尚未入账，connections 无从落地（历史实现此处会拿硬编码"
            "号段顶替，写出悬空边）。" % (demo_q, missing, AXIOMS_JSON))
    axioms, rich = [], []
    for j, (pid, text, hexa, src) in enumerate(laws):
        mid = "M-%06d" % (start + j)
        pmap[pid] = mid
        ev = [sym[hexa]] if hexa in sym else [anchors["hub"], anchors["atlas"]]
        conf = 0.75 if "待补" in src else 0.85
        content = "【源·%s】%s｜归%s卦｜据库：%s" % (pid, text, hexa, src)
        axioms.append({"id": pid, "text": text, "hex": hexa,
                       "mid": mid, "evidence": ev, "ref": "corpus:%s" % src})
        rich.append({"url": "axiom://%s" % pid,
                     "title": "源%s·%s" % (pid, text[:20]),
                     "content": content, "domain": "source-core",
                     "memory_type": "Pattern", "confidence": conf,
                     "connections": ev})
    demo_conns = [pmap[p] for p in demo_uses]
    if xrefs:
        by_pid = {}
        for r, (pid, _, _, _) in zip(rich, laws):
            by_pid[pid] = r
        for pid, refs in xrefs.items():
            if pid in by_pid:
                for x in refs:
                    m = resolve_ref(x, pmap, anchors)
                    if m and m not in by_pid[pid]["connections"]:
                        by_pid[pid]["connections"].append(m)
    rich.append({"url": "axiom://demo-%s" % demo_q[:6],
                 "title": "源推演·%s" % demo_q,
                 "content": "【源推演·%s】%s" % (demo_q, demo_a),
                 "domain": "source-core", "memory_type": "Causal",
                 "confidence": 0.75, "connections": demo_conns})
    with open(AXIOMS_JSON, encoding="utf-8") as fh:
        old = json.load(fh)
    old += axioms
    with open(AXIOMS_JSON, "w", encoding="utf-8") as fh:
        json.dump(old, fh, ensure_ascii=False, indent=1)
    with open(outfile, "w", encoding="utf-8") as fh:
        for r in rich:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("laws=%d demo=1 rich=%d start=M-%06d end=M-%06d axioms_total=%d" % (
        len(laws), len(rich), start, start + len(rich) - 1, len(old)))
    return start


