    assert resolve_ref(REF_HUB, {}, anchors) == anchors["hub"]
    assert resolve_ref(REF_ATLAS, {}, anchors) == anchors["atlas"]
    assert resolve_ref("P01", {"P01": "M-000001"}, anchors) == "M-000001"
    assert resolve_ref("P404", {}, anchors) == ""
    try:
        prior_pmap("/nonexistent/axioms.json", known)
    except SystemExit:
        pass
    else:
        raise AssertionError("缺账本未中止（会退回号段猜测）")
    with tempfile.TemporaryDirectory() as td:
        good = os.path.join(td, "good.json")
