_MID_LINE = re.compile(r'^"id": "(M-\d{6})"')
_HEAD_LINE = re.compile(r'^"content": "(.{0,40})')
_DOM_LINE = re.compile(r'^"domain": "([^"]*)"')
_MID_BYTES = re.compile(rb'"id": "(M-\d{6})"')


def iter_symbol_memories(path=None):
    """流式吐 neuro-symbols 记忆的 (M-id, content 前 40 字)。

    cocoons.json 是 52MB 缩进 JSON，逐字段独占一行，故按行扫即可，
    不必全量 parse（与 nt_hf_digest_to_cocoons.scan_max_mid 同口径）。
    path 缺省**调用时**才取 COCOONS（不在签名里绑死）：绑死等于导入时快照，
    换库/测试都无法覆盖。
    """
    path = path or COCOONS
    try:
        with open(path, encoding="utf-8") as fh:
            mid = head = None
            for raw in fh:
                ln = raw.strip()
                m = _MID_LINE.match(ln)
                if m:
                    mid = m.group(1)
                    continue
                m = _HEAD_LINE.match(ln)
                if m:
                    head = m.group(1)
                    continue
                m = _DOM_LINE.match(ln)
                if m:
                    if m.group(1) == SYMBOL_DOMAIN and mid and head:
                        yield mid, head
                    mid = head = None
    except OSError as e:
        raise SystemExit(
            "ABORT: 读不到活库 %s（%s）—— 无法反查卦符 M-id。硬编码号段"
            "（档案期 477231…480475）在活库从不存在，只会写出悬空边。"
            % (path, e))


def live_symbol_mids(path=None):
    """卦名 → 活库 neuro-symbols 记忆 M-id（20 点亮符）。

    反查不到即 SystemExit：宁可停，也不编 id。
    """
    path = path or COCOONS
    table = {}
    for mid, head in iter_symbol_memories(path):
        if len(head) < 2 or head.startswith(ATLAS_PREFIX):
            continue
        ch = head[0]
        if len(ch) != 1 or not HEXAGRAM_BASE <= ord(ch) < HEXAGRAM_BASE + 64:
            continue
        rest = head[1:]
        cut = min([rest.find(t) for t in TRIGRAMS if t in rest] or [-1])
        name = rest if cut < 0 else rest[:cut]
        if name:
            table.setdefault(name, mid)
    if not table:
        raise SystemExit(
            "ABORT: %s 内 domain=%s 的卦符记忆 0 条 —— 反查失败，拒绝回退"
            "硬编码 M-id（该号段在活库不存在）。" % (path, SYMBOL_DOMAIN))
    return table


def live_atlas_mid(path=None):
    """64卦全图总纲的活库 M-id；查不到即 SystemExit。"""
    path = path or COCOONS
    for mid, head in iter_symbol_memories(path):
        if head.startswith(ATLAS_PREFIX):
            return mid
    raise SystemExit(
        "ABORT: %s 内找不到 %s 域的全图总纲记忆（content 以 %r 开头）—— "
        "拒绝回退硬编码 M-id。" % (path, SYMBOL_DOMAIN, ATLAS_PREFIX))


def live_mid_set(path=None):
    """活库全部 M-id 集合（流式字节扫，不 parse 52MB JSON）。

    用途：账本/外部元数据里引用的 id 必须在此集合内，否则即为悬空边。
    """
    path = path or COCOONS
    try:
        with open(path, "rb") as fh:
            return {m.decode() for m in _MID_BYTES.findall(fh.read())}
    except OSError as e:
        raise SystemExit("ABORT: 读不到活库 %s（%s）—— 无法校验引用的 M-id。"
                         % (path, e))


